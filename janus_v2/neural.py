"""neural.py — Janus's own brain: a transformer trained from scratch, locally.

No borrowed weights, no API. Training data is generated by Janus itself
(curriculum families with programmatic ground truth, formatted as traces).
Weights live in data/brain.pt and are Janus's alone. The neural reasoner
enters the registry only through the eval gate, like every capability.
Train: python -m janus_v2.neural --steps 1200
"""
from __future__ import annotations

import argparse
import json
import math
import random
import sys
import time
from pathlib import Path

import torch
import torch.nn as nn

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
HERE = Path(__file__).parent
CKPT = HERE / "data" / "brain.pt"
DEVICE = "mps" if torch.backends.mps.is_available() else "cpu"


def gen_examples(rng: random.Random, n: int) -> list[str]:
    """Self-generated traces: question -> worked answer. Ground truth by construction."""
    out = []
    for _ in range(n):
        fam = rng.choice(["percent", "average", "arith-seq", "factorial", "gcd",
                          "area", "interest", "pe", "fcf", "speed"])
        a, b, c = rng.randint(2, 99), rng.randint(2, 60), rng.randint(2, 12)
        if fam == "percent":
            q, ans = f"What is {a} percent of {b * 10}?", f"{a}% of {b * 10} = {a * b / 10:g}"
        elif fam == "average":
            q, ans = f"What is the average of {a}, {b}, and {c * 3}?", \
                     f"Average = {(a + b + c * 3) / 3:g}"
        elif fam == "arith-seq":
            s = [a + k * c for k in range(5)]
            q, ans = (f"What is the next number in the sequence {', '.join(map(str, s))}?",
                      f"Next number = {s[-1] + c}")
        elif fam == "factorial":
            k = rng.randint(3, 8)
            q, ans = f"What is the factorial of {k}?", f"{k}! = {math.factorial(k)}"
        elif fam == "gcd":
            q, ans = (f"What is the greatest common divisor of {a * 2} and {b * 2}?",
                      f"GCD = {math.gcd(a * 2, b * 2)}")
        elif fam == "area":
            q, ans = (f"If a rectangle has length {a} and width {b}, what is its area?",
                      f"Area = {a * b}")
        elif fam == "interest":
            q, ans = (f"What is the simple interest on ${a * 100} at {c}% per year for 2 years?",
                      f"Simple interest = ${a * c * 2:g}")
        elif fam == "pe":
            q, ans = (f"A stock trades at ${a * 3} with EPS of ${c}. What is its P/E ratio?",
                      f"P/E ratio = {a * 3 / c:g}")
        elif fam == "fcf":
            q, ans = (f"Operating cash flow is ${a * 10} and capital expenditure is ${b * 5}. "
                      f"What is free cash flow?", f"Free cash flow = ${a * 10 - b * 5:g}")
        else:
            q, ans = (f"A train travels {a * 4} km in {c} hours. What is its average speed in km/h?",
                      f"Average speed = {a * 4 / c:g} km/h")
        out.append(f"Q: {q} A: {ans}<END>")
    return out


class Brain(nn.Module):
    def __init__(self, vocab: int, d: int = 192, heads: int = 6, layers: int = 4, maxlen: int = 128):
        super().__init__()
        self.emb = nn.Embedding(vocab, d)
        self.pos = nn.Embedding(maxlen, d)
        enc = nn.TransformerEncoderLayer(d, heads, d * 4, batch_first=True)
        self.tr = nn.TransformerEncoder(enc, layers)
        self.head = nn.Linear(d, vocab)
        self.maxlen = maxlen

    def forward(self, x):
        pos = torch.arange(x.size(1), device=x.device)
        mask = torch.triu(torch.ones(x.size(1), x.size(1), device=x.device) * float("-inf"), 1)
        h = self.tr(self.emb(x) + self.pos(pos), mask=mask)
        return self.head(h)


def _tokenizer(texts: list[str]):
    chars = sorted(set("".join(texts)) | set("Q:A<END>0123456789.,%$=? "))
    stoi = {ch: i + 1 for i, ch in enumerate(chars)}
    return stoi, {i: ch for ch, i in stoi.items()}


def train(steps: int = 1200, n_data: int = 6000, seed: int = 5) -> dict:
    rng = random.Random(seed)
    texts = gen_examples(rng, n_data)
    stoi, itos = _tokenizer(texts)
    vocab = len(stoi) + 1
    data = [torch.tensor([stoi.get(ch, 0) for ch in t[:120]], dtype=torch.long) for t in texts]
    model = Brain(vocab).to(DEVICE)
    params = sum(p.numel() for p in model.parameters())
    opt = torch.optim.AdamW(model.parameters(), lr=2e-3)
    losses = []
    t0 = time.time()
    for step in range(steps):
        batch = random.sample(data, 32)
        maxlen = max(len(x) for x in batch)
        x = torch.zeros(32, maxlen, dtype=torch.long)
        for i, seq in enumerate(batch):
            x[i, :len(seq)] = seq
        x = x.to(DEVICE)
        logits = model(x[:, :-1])
        loss = nn.functional.cross_entropy(
            logits.reshape(-1, vocab), x[:, 1:].reshape(-1), ignore_index=0)
        opt.zero_grad()
        loss.backward()
        opt.step()
        losses.append(round(loss.item(), 3))
        if step % 300 == 0:
            print(f"step {step} loss {loss.item():.3f}")
    CKPT.parent.mkdir(parents=True, exist_ok=True)
    torch.save({"state": model.state_dict(), "stoi": stoi, "itos": itos,
                "params": params, "final_loss": losses[-1]}, CKPT)
    result = {"params": params, "steps": steps, "final_loss": losses[-1],
              "seconds": round(time.time() - t0, 1), "device": DEVICE,
              "checkpoint": str(CKPT)}
    print(json.dumps(result))
    return result


@torch.no_grad()
def generate(question: str, max_new: int = 48) -> str | None:
    if not CKPT.exists():
        return None
    blob = torch.load(CKPT, map_location=DEVICE, weights_only=False)
    stoi, itos = blob["stoi"], blob["itos"]
    model = Brain(len(stoi) + 1).to(DEVICE)
    model.load_state_dict(blob["state"])
    model.eval()
    ids = [stoi.get(ch, 0) for ch in f"Q: {question} A:"][:110]
    x = torch.tensor([ids], dtype=torch.long, device=DEVICE)
    out = []
    for _ in range(max_new):
        nxt = int(model(x)[0, -1].argmax())
        ch = itos.get(nxt, "")
        if ch == "<" or "".join(out).endswith("<END"):
            break
        out.append(ch)
        x = torch.cat([x, torch.tensor([[nxt]], device=DEVICE)], dim=1)
    text = "".join(out).replace("<END>", "").strip()
    return text or None


def neural_answer(question: str):
    """Registry-shaped answer from Janus's own weights."""
    text = generate(question)
    if not text:
        return None
    return text, 0.55, "neural.brain-v1"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--steps", type=int, default=1200)
    ap.add_argument("--ask", default=None)
    args = ap.parse_args()
    if args.ask:
        print(generate(args.ask))
    else:
        train(args.steps)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
